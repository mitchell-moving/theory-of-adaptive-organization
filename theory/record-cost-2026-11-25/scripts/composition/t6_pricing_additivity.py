"""Toy 6 (steering task 2): capacity pricing vs parameter pricing, settled by additivity for independent records.
Requirement A (no heat): the price of holding two independent records is the sum of the prices.
 - For a price that depends on the system only through N (capacity) or K (parameter count), and composites
   with N_AB = N_A N_B (resp. K_AB = K_A K_B), additivity is the functional equation f(mn) = f(m) + f(n).
 - Monotone solutions on the positive integers are f = c*log (proof in NOTE.md, squeeze argument).
Checks here:
 (1) capacities N_A, N_AB for classical bit, qubit, rebit, gbit (2-gbit capacity computed by LP over vertex subsets).
 (2) which prices are additive in each theory: c*log N, c*log K, linear K (sibling's 'dimension pricing'), K-1.
 (3) re-rank the sibling's single-system table (nocloning/NOTE.md sec.3) under each additive price.
"""
import itertools, json, numpy as np
from scipy.optimize import linprog
idx = lambda a, b, x, y: ((a*2+b)*2+x)*2+y
def table(f):
    p = np.zeros(16)
    for a, b, x, y in itertools.product(range(2), repeat=4): p[idx(a, b, x, y)] = f(a, b, x, y)
    return p
V = [table(lambda a, b, x, y, al=al, be=be: float(a == al[x] and b == be[y])) for al in itertools.product(range(2), repeat=2) for be in itertools.product(range(2), repeat=2)]
V += [table(lambda a, b, x, y, al=al, be=be, g=g: 0.5*float((a ^ b) == ((x*y) ^ (al*x) ^ (be*y) ^ g))) for al, be, g in itertools.product(range(2), repeat=3)]
V = np.array(V)
def distinguishable(S):
    """effects e_k = sum_j c_kj pi_j (c>=0; generated by product effects = dual of the maximal state space),
    sum_k e_k = unit on all vertices, e_k(v_S[m]) = delta_km."""
    m = len(S); nv = 16*m; Aeq, beq = [], []
    for v in V:
        row = np.zeros(nv)
        for k in range(m): row[16*k:16*(k+1)] = v
        Aeq.append(row); beq.append(1.0)
    for k in range(m):
        for j, s in enumerate(S):
            row = np.zeros(nv); row[16*k:16*(k+1)] = V[s]; Aeq.append(row); beq.append(1.0 if j == k else 0.0)
    r = linprog(np.zeros(nv), A_eq=np.array(Aeq), b_eq=np.array(beq), bounds=[(0, None)]*nv, method="highs")
    return r.status == 0
cap = 1
for m in range(2, 7):
    hit = None
    for S in itertools.combinations(range(24), m):
        if distinguishable(S): hit = S; break
    if hit is None: break
    cap = m; witness = hit
out = {"gbit_pair_capacity_N_AB": cap, "witness_vertices": list(witness)}
theories = {"classical bit": (2, 4, 2, 4), "qubit": (2, 4, 4, 16), "rebit": (2, 4, 3, 10), "gbit": (2, cap, 3, 9)}
rows = {}
for name, (NA, NAB, KA, KAB) in theories.items():
    rows[name] = dict(N_A=NA, N_AB=NAB, K_A=KA, K_AB=KAB,
        logN_additive=bool(np.isclose(np.log2(NAB), 2*np.log2(NA))),
        logK_additive=bool(np.isclose(np.log2(KAB), 2*np.log2(KA))),
        linearK_additive=bool(KAB == 2*KA),
        Kminus1_additive=bool(KAB-1 == 2*(KA-1)))
out["additivity"] = rows
# sibling table (nocloning/NOTE.md sec.3): later-question error at zero drift
sib = {"classical N=2": (2, 2, 0.250), "classical N=3": (3, 3, 0.167), "classical N=4": (4, 4, 0.125),
       "square (gbit)": (2, 3, 0.125), "hexagon": (2, 3, 0.167), "disk (rebit)": (2, 3, 0.1817), "ball (qubit)": (2, 4, 0.1817)}
q = 4.0
rank = {}
for price in ["log2 N", "log2 K"]:
    J = {k: (np.log2(N) if price == "log2 N" else np.log2(K)) + q*e for k, (N, K, e) in sib.items()}
    rank[price] = sorted(((round(v, 4), k) for k, v in J.items()))
out["sibling_table_reranked_q4"] = rank
json.dump(out, open("outputs/t6_pricing_additivity.json", "w"), indent=1); print(json.dumps(out, indent=1))
