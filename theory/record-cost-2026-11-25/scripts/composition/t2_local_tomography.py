"""Toy 2 (Q1): local tomography as 'cheap local reading of joint records'.
K = number of real parameters fixing an (unnormalised) state; local tomography <=> K_AB = K_A*K_B
(the joint state is fixed by products of local reads). Computed by rank of the span of product effects
against the full joint effect space, for classical bits, rebits (real QM), qubits, gbits (boxworld).
Then an explicit rebit pair of records that are perfectly distinguishable globally but have IDENTICAL
statistics for every product of local real measurements (so reading them needs a joint operation: a link cost L).
"""
import itertools, json, numpy as np
out = {}
I = np.eye(2); X = np.array([[0, 1], [1, 0]]); Z = np.diag([1, -1]); Y = np.array([[0, -1j], [1j, 0]])
def herm_basis(n, real):
    B = []
    for i in range(n):
        M = np.zeros((n, n), complex); M[i, i] = 1; B.append(M)
    for i, j in itertools.combinations(range(n), 2):
        M = np.zeros((n, n), complex); M[i, j] = M[j, i] = 1; B.append(M)
        if not real:
            M = np.zeros((n, n), complex); M[i, j] = -1j; M[j, i] = 1j; B.append(M)
    return B
def vec(M, real): 
    v = np.r_[M.real.ravel(), M.imag.ravel()]; return v
for name, real in [("qubit", False), ("rebit", True)]:
    loc = herm_basis(2, real); joint = herm_basis(4, real)
    prods = [np.kron(a, b) for a in loc for b in loc]
    rk = np.linalg.matrix_rank(np.array([vec(p, real) for p in prods]))
    out[name] = dict(K_A=len(loc), K_AB=len(joint), K_A_squared=len(loc)**2, span_of_local_products=int(rk),
                     locally_tomographic=bool(rk == len(joint)))
out["classical_bit"] = dict(K_A=2, K_AB=4, K_A_squared=4, locally_tomographic=True)
# gbit pair: tables p(a,b|x,y) in the no-signalling subspace; K_AB = dim(span of the 24 vertices)
idx = lambda a, b, x, y: ((a*2+b)*2+x)*2+y
def table(f):
    p = np.zeros(16)
    for a, b, x, y in itertools.product(range(2), repeat=4): p[idx(a, b, x, y)] = f(a, b, x, y)
    return p
Vs = [table(lambda a, b, x, y, al=al, be=be: float(a == al[x] and b == be[y])) for al in itertools.product(range(2), repeat=2) for be in itertools.product(range(2), repeat=2)]
Vs += [table(lambda a, b, x, y, al=al, be=be, g=g: 0.5*float((a ^ b) == ((x*y) ^ (al*x) ^ (be*y) ^ g))) for al, be, g in itertools.product(range(2), repeat=3)]
KAB = np.linalg.matrix_rank(np.array(Vs))
out["gbit"] = dict(K_A=3, K_AB=int(KAB), K_A_squared=9, locally_tomographic=bool(KAB == 9),
                   note="boxworld effects are generated by products of local effects, so joint states are fixed by local reads")
# rebit hidden record
YY = np.kron(Y, Y).real  # real symmetric
rho_p = (np.eye(4) + YY)/4; rho_m = (np.eye(4) - YY)/4
eig = [np.linalg.eigvalsh(r).round(6).tolist() for r in (rho_p, rho_m)]
rng = np.random.default_rng(0)
maxdiff = 0
for _ in range(20000):  # random real local effects (projectors on random real directions) and products
    th1, th2 = rng.uniform(0, np.pi, 2)
    P1 = np.outer([np.cos(th1), np.sin(th1)], [np.cos(th1), np.sin(th1)])
    P2 = np.outer([np.cos(th2), np.sin(th2)], [np.cos(th2), np.sin(th2)])
    E = np.kron(P1, P2); maxdiff = max(maxdiff, abs(np.trace(E @ (rho_p - rho_m))))
tracedist = 0.5*np.abs(np.linalg.eigvalsh(rho_p - rho_m)).sum()
# qubit: same two states, local Y x Y measurement distinguishes them perfectly
Py = [(np.eye(2) + s*Y)/2 for s in (1, -1)]
pq = {lab: [np.trace(np.kron(Py[i], Py[j]) @ r).real.round(6) for i in range(2) for j in range(2)] for lab, r in (("plus", rho_p), ("minus", rho_m))}
out["rebit_hidden_record"] = dict(states="rho_pm = (I +/- Y(x)Y)/4 (real, equal mixtures of two Bell states)",
    eigenvalues=eig, max_local_product_stat_difference_over_20000_random_real_product_effects=float(maxdiff),
    global_trace_distance=float(tracedist),
    qubit_local_YY_outcome_probs=pq,
    reading="perfectly distinguishable as a whole, invisible to every product of local real reads: reading it needs a joint operation (link cost L). With qubits the same pair is read perfectly by local Y reads plus comparing outcomes.")
json.dump(out, open("outputs/t2_local_tomography.json", "w"), indent=1, default=str)
print(json.dumps(out, indent=1, default=str))
